def _node(n, depth, open_=False):
    t = html.escape(n["t"])
    b = html.escape(n["b"], quote=True)
    link = html.escape(n["link"], quote=True)
    tags = ",".join(str(x) for x in n["tags"])
    kids = n["children"]
    cls = "km-node" + (" km-open" if open_ else "")
    out = [f'<li class="{cls}" data-depth="{depth}">']
    out.append('<div class="km-row">')
    if kids:
        out.append(f'<button class="km-toggle" type="button" aria-expanded="{str(open_).lower()}" aria-label="展开或收起"></button>')
    else:
        out.append('<span class="km-dot" aria-hidden="true"></span>')
    out.append(f'<button class="km-label" type="button" data-brief="{b}" data-link="{link}" data-tags="{tags}">'
               f'<span class="km-name">{t}</span><span class="km-brief">{html.escape(n["b"])}</span></button>')
    out.append('</div>')
    out.append(f'<div class="km-detail" hidden>{html.escape(n["d"])}</div>')
    if kids:
        out.append('<ul class="km-children">')
        for c in kids:
            out.append(_node(c, depth + 1, False))
        out.append('</ul>')
    out.append('</li>')
    return "".join(out)


